/**
 * Locale para fechas y horas: "12 sept" en español,
 * "Sep 12" en inglés.
 */
export function locale(): string {
  return idiomaActual() === "en" ? "en-US" : "es-CO";
}

/**
 * Texto en el idioma elegido. Las llaves se validan en
 * compilación: si falta una traducción, `tsc` se queja.
 */
export function t(
  clave: Clave,
  variables?: Record<string, string | number>,
): string {
  const tabla = (idiomaActual() === "en" ? EN : ES) as Record<Clave, string>;

  let texto: string = tabla[clave] ?? clave;

  if (variables) {
    for (const [nombre, valor] of Object.entries(variables)) {
      texto = texto.split(`{${nombre}}`).join(String(valor));
    }
  }

  return texto;
}
